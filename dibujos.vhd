    END FUNCTION letra;

    FUNCTION texto_pixel (
        msg : STRING;
        x,
        y : INTEGER
    ) RETURN BOOLEAN IS

        VARIABLE n : INTEGER;

    BEGIN

        IF (x < 0 OR x >= msg'length * 12 OR y < 0 OR y >= 14) THEN
            RETURN FALSE;
        END IF;

        FOR i IN 0 TO msg'length - 1 LOOP

            IF (x >= i * 12 AND x < (i + 1) * 12) THEN
                RETURN letra(msg(msg'low + i), (x - i * 12) / 2, y / 2);
            END IF;

        END LOOP;

        RETURN FALSE;

    END FUNCTION texto_pixel;

    FUNCTION digito_pixel (
        d,
        x,
        y : INTEGER
    ) RETURN BOOLEAN IS
    BEGIN

        IF (d < 0 OR d > 9 OR x < 0 OR x >= 12 OR y < 0 OR y >= 14) THEN
            RETURN FALSE;
        END IF;

        RETURN letra(CHARACTER'val(CHARACTER'pos('0') + d), x / 2, y / 2);

    END FUNCTION digito_pixel;

